const DICTS: Record<Lang, Dict> = { en, es, de, fr, pt, ur, bn, th, ar };

function applyDir(): void {
  document.documentElement.dir = lang === "ar" || lang === "ur" ? "rtl" : "ltr";
}

function readStored(): Lang {
  const v = localStorage.getItem("px-lang");
  return v && v in DICTS ? (v as Lang) : "en";
}

let lang: Lang = readStored();

export function getLang(): Lang {
  return lang;
}

export function setLang(next: string): Lang {
  lang = next in DICTS ? (next as Lang) : "en";
  localStorage.setItem("px-lang", lang);
  document.documentElement.lang = lang;
  applyDir();
  return lang;
}

/** Translate a key; falls back to English, then to the key itself. */
export function t(key: string): string {
  return DICTS[lang][key] ?? en[key] ?? key;
}

